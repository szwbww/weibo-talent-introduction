CREATE TABLE discovery_paper_reprocess_run (
    execution_id BIGINT NOT NULL PRIMARY KEY,
    source_execution_id BIGINT NOT NULL,
    request_key CHAR(36) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    active_key VARCHAR(32) NULL,
    mode VARCHAR(16) NOT NULL,
    state VARCHAR(32) NOT NULL,
    phase VARCHAR(16) NOT NULL,
    scope_json MEDIUMTEXT NOT NULL,
    revision BIGINT NOT NULL DEFAULT 0,
    lease_token VARCHAR(64) NULL,
    lease_until DATETIME(3) NULL,
    generation BIGINT NOT NULL DEFAULT 0,
    cancel_requested TINYINT(1) NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    finished_at DATETIME(3) NULL,
    UNIQUE KEY uk_paper_reprocess_request (request_key),
    UNIQUE KEY uk_paper_reprocess_active (active_key),
    INDEX idx_paper_reprocess_source (source_execution_id, execution_id),
    CONSTRAINT chk_paper_reprocess_mode CHECK (mode IN ('AUDIT','ENFORCE')),
    CONSTRAINT chk_paper_reprocess_state CHECK (state IN ('PREPARING','RUNNING','CANCELLING','COMPLETED','COMPLETED_WITH_ERRORS','FAILED','INTERRUPTED','CANCELLED')),
    CONSTRAINT chk_paper_reprocess_phase CHECK (phase IN ('FREEZE','READ','PARSE','BIND','APPLY','REVIEW','SAVE')),
    CONSTRAINT chk_paper_reprocess_active CHECK ((state IN ('PREPARING','RUNNING','CANCELLING') AND active_key IS NOT NULL AND active_key = 'PAPER_REPROCESS') OR (state NOT IN ('PREPARING','RUNNING','CANCELLING') AND active_key IS NULL)),
    CONSTRAINT chk_paper_reprocess_revision CHECK (revision >= 0 AND generation >= 0),
    CONSTRAINT chk_paper_reprocess_scope_size CHECK (OCTET_LENGTH(scope_json) <= 4194304)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE discovery_paper_reprocess_item (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    execution_id BIGINT NOT NULL,
    kind VARCHAR(8) NOT NULL,
    item_key VARCHAR(128) NOT NULL,
    state VARCHAR(16) NOT NULL,
    input_json MEDIUMTEXT NOT NULL,
    result_json MEDIUMTEXT NULL,
    lease_token VARCHAR(64) NULL,
    lease_until DATETIME(3) NULL,
    generation BIGINT NOT NULL DEFAULT 0,
    revision BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    completed_at DATETIME(3) NULL,
    UNIQUE KEY uk_paper_reprocess_item (execution_id, kind, item_key),
    INDEX idx_paper_reprocess_item_run (execution_id, kind, state, id),
    INDEX idx_paper_reprocess_item_lease (state, lease_until, id),
    CONSTRAINT chk_paper_reprocess_item_kind CHECK (kind IN ('PAPER','TARGET')),
    CONSTRAINT chk_paper_reprocess_item_state CHECK (state IN ('PENDING','RUNNING','COMPLETE','ERROR','SKIPPED','CANCELLED')),
    CONSTRAINT chk_paper_reprocess_item_revision CHECK (revision >= 0 AND generation >= 0),
    CONSTRAINT chk_paper_reprocess_input_size CHECK (OCTET_LENGTH(input_json) <= 4194304),
    CONSTRAINT chk_paper_reprocess_result_size CHECK (result_json IS NULL OR OCTET_LENGTH(result_json) <= 4194304)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
